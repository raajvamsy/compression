"""Real bitstream check: encode every image to a .ffic file, decode it, compare bytes with the original.

    python roundtrip.py DATADIR [config-id ...]     (ids from CONFIGS below; default: all)

Writes experiments/roundtrip.json and experiments/ROUNDTRIP.md: real file size (header included) vs the ideal code length the
experiments log, vs JPEG XL e9, encode and decode wall time, and whether the decoded pixels are bit-exact.
"""
import hashlib, json, os, re, subprocess, sys, tempfile, time
from concurrent.futures import ThreadPoolExecutor
from experiments import MB

HERE = os.path.dirname(os.path.abspath(__file__)); EXE = os.path.join(HERE, "ffic")
OUT = os.path.join(HERE, "experiments")
CONFIGS = {
    "best_now": (MB, 4, "best single coder, layers one after another"),
    "pipe": (MB + " pipe=1 snapk=32", 2, "staggered colour pipeline (3 threads)"),
    "inter_cmatch_excl_inf": (MB + " inter=1 cmatch=1 mexcl=1 minf=1 snapk=32", 2, "pixel by pixel + whole-colour match + exclusion"),
}


def one(D, tmp, name, w, h, cfg):
    src = f"{D}/{name}.rgb"; enc = f"{tmp}/{name}.ffic"; dec = f"{tmp}/{name}.out.rgb"
    t0 = time.time(); out = subprocess.check_output([EXE, src, str(w), str(h)] + cfg.split() + [f"out={enc}"], text=True); te = time.time() - t0
    t0 = time.time(); subprocess.check_output([EXE, "-d", enc, dec], text=True); td = time.time() - t0
    v = dict(re.findall(r"(\w+)=([-\d.]+)", out))
    ok = open(src, "rb").read() == open(dec, "rb").read()
    size = os.path.getsize(enc); os.remove(enc); os.remove(dec)
    return {"file": size, "ideal": round(float(v["bytes"])), "enc_s": round(te, 2), "dec_s": round(td, 2), "exact": ok}


def main():
    D = sys.argv[1]; ids = sys.argv[2:] or list(CONFIGS)
    subprocess.check_call(["clang", "-O2", "-march=native", "-pthread", "-o", EXE, os.path.join(HERE, "ffic.c"), "-lm"])
    ref = json.load(open(os.path.join(D, "ref.json"))); jxl = sum(r["jxl9"] for r in ref.values())
    path = os.path.join(OUT, "roundtrip.json"); res = json.load(open(path)) if os.path.exists(path) else {}
    sha = hashlib.sha1(open(os.path.join(HERE, "ffic.c"), "rb").read()).hexdigest()[:10]
    with tempfile.TemporaryDirectory() as tmp:
        for cid in ids:
            cfg, jobs, desc = CONFIGS[cid]
            with ThreadPoolExecutor(jobs) as pool:
                futs = {n: pool.submit(one, D, tmp, n, r["w"], r["h"], cfg) for n, r in ref.items()}
                per = {n: f.result() for n, f in futs.items()}
            tf = sum(p["file"] for p in per.values()); ti = sum(p["ideal"] for p in per.values())
            res[cid] = {"cfg": cfg, "desc": desc, "code_sha1": sha, "date": time.strftime("%Y-%m-%d %H:%M:%S"), "per_image": per,
                        "file": tf, "ideal": ti, "all_exact": all(p["exact"] for p in per.values()),
                        "vs_jxl9_pct": round(100 * (tf / jxl - 1), 3), "overhead_pct": round(100 * (tf / ti - 1), 3),
                        "enc_s": round(sum(p["enc_s"] for p in per.values()), 1), "dec_s": round(sum(p["dec_s"] for p in per.values()), 1)}
            r = res[cid]
            print(f"{cid:24} file {tf:>11,} B  ideal {ti:>11,} B  (+{r['overhead_pct']:.3f}%)  {r['vs_jxl9_pct']:+.2f}% vs JXL  "
                  f"enc {r['enc_s']:.0f}s dec {r['dec_s']:.0f}s  exact {sum(p['exact'] for p in per.values())}/{len(per)}", flush=True)
    json.dump(res, open(path, "w"), indent=1)
    # per-photo choice between the stored configurations (1 extra byte would name it; the header's option string already does)
    L = ["# FFIC real bitstream: round trip", "",
         "Generated by `ffic/roundtrip.py`. Every image is encoded to a real `.ffic` file (header with the options + three arithmetic-coded",
         "streams, one per colour layer), decoded with `ffic -d`, and compared byte for byte with the original.",
         "Sizes include the header. Times are wall seconds summed over the 20 images.", "",
         "| config | what | file bytes | ideal bytes | coder overhead | vs JXL e9 | encode s | decode s | bit-exact |", "|---|---|---|---|---|---|---|---|---|"]
    for cid, r in res.items():
        L.append(f"| `{cid}` | {r['desc']} | {r['file']:,} | {r['ideal']:,} | +{r['overhead_pct']:.3f}% | {r['vs_jxl9_pct']:+.2f}% | {r['enc_s']:.0f} | {r['dec_s']:.0f} | "
                 f"{'yes, ' + str(len(r['per_image'])) + '/' + str(len(r['per_image'])) if r['all_exact'] else 'NO'} |")
    if len(res) > 1:
        names = list(ref); pick = {n: min(res, key=lambda c: res[c]["per_image"][n]["file"]) for n in names}
        tot = sum(res[pick[n]]["per_image"][n]["file"] for n in names)
        L += ["", f"Smallest real file per photo (the decoder reads the options from the header, so no extra signal): **{tot:,} B = "
              f"{100 * (tot / jxl - 1):+.2f}% vs JXL e9**. Picks: " + ", ".join(f"`{c}` x{sum(1 for n in names if pick[n] == c)}" for c in res), ""]
    L += ["## Per image", "", "| image | JXL e9 | " + " | ".join(f"`{c}` file | exact" for c in res) + " |", "|---|---" + "|---|---" * len(res) + "|"]
    for n in ref:
        L.append(f"| {n} | {ref[n]['jxl9']:,} | " + " | ".join(f"{res[c]['per_image'][n]['file']:,} | {'yes' if res[c]['per_image'][n]['exact'] else 'NO'}" for c in res) + " |")
    open(os.path.join(OUT, "ROUNDTRIP.md"), "w").write("\n".join(L) + "\n"); print("wrote experiments/ROUNDTRIP.md")


if __name__ == "__main__":
    main()
