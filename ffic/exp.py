"""Experiment runner with a permanent log.

    python exp.py DATADIR ID [ID ...]      run experiments by id (see experiments.py), append to experiments/log.jsonl
    python exp.py DATADIR --all            run every experiment not yet in the log for the current code fingerprint
    python exp.py DATADIR --report         only regenerate experiments/LOG.md

Every record keeps: id, mechanism, FunnelBrain source, hypothesis, config, code fingerprint (sha1 of ffic.c + git HEAD),
per-image bytes / per-plane bytes / ms / mechanism stats, totals vs JXL e9, vs FunnelZip (Pexels subset) and vs the
reference experiment, wins/losses per image, and an automatic verdict.
"""
import hashlib, json, os, re, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor
from experiments import EXPERIMENTS, REFERENCE

HERE = os.path.dirname(os.path.abspath(__file__))
LOGDIR = os.path.join(HERE, "experiments"); LOG = os.path.join(LOGDIR, "log.jsonl"); MD = os.path.join(LOGDIR, "LOG.md")
EXE = os.path.join(HERE, "ffic")


def fingerprint():
    src = open(os.path.join(HERE, "ffic.c"), "rb").read()
    head = subprocess.run(["git", "-C", HERE, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    return hashlib.sha1(src).hexdigest()[:10], head


def build():
    subprocess.check_call(["clang", "-O2", "-march=native", "-o", EXE, os.path.join(HERE, "ffic.c"), "-lm"])


def funnelzip_sizes(D):
    fz, cur = {}, None
    try:
        for line in open(os.path.join(D, "..", "pexels.log")):
            m = re.match(r"== (p\d+)\.jpg", line)
            if m: cur = "pex_" + m.group(1)
            m = re.search(r"FunnelZip \(raw pixels\)\s+([\d,]+) B", line)
            if m and cur: fz[cur] = int(m.group(1).replace(",", ""))
    except FileNotFoundError:
        pass
    return fz


def run_one(D, ref, name, cfg):
    r = ref[name]
    out = subprocess.check_output([EXE, f"{D}/{name}.rgb", str(r["w"]), str(r["h"])] + cfg.split(), text=True)
    vals = {k: float(v) for k, v in re.findall(r"(\w+)=([-\d.eE+naif]+)", out)}
    return vals


def load_log():
    if not os.path.exists(LOG): return []
    return [json.loads(l) for l in open(LOG) if l.strip()]


def run_experiment(D, exp):
    if exp.get("data"): D = os.path.join(os.path.dirname(D.rstrip('/')), exp["data"])
    ref = json.load(open(os.path.join(D, "ref.json"))); fz = funnelzip_sizes(os.path.join(os.path.dirname(D.rstrip('/')), 'ffic_data'))
    t0 = time.time()
    with ThreadPoolExecutor(4) as pool:
        futs = {n: pool.submit(run_one, D, ref, n, exp["cfg"]) for n in ref}
        per = {n: f.result() for n, f in futs.items()}
    wall = time.time() - t0
    fp, head = fingerprint()
    tot = sum(v["bytes"] for v in per.values()); jxl = sum(r["jxl9"] for r in ref.values())
    pex = [n for n in ref if n in fz]
    rec = {
        "id": exp["id"], "group": exp.get("group", ""), "mechanism": exp["mechanism"], "funnelbrain": exp["funnelbrain"],
        "hypothesis": exp["hypothesis"], "cfg": exp["cfg"], "data": exp.get("data", "ffic_data"), "code_sha1": fp, "git_head": head,
        "date": time.strftime("%Y-%m-%d %H:%M:%S"), "wall_s": round(wall, 1),
        "cpu_s": round(sum(v["ms"] for v in per.values()) / 1000, 1),
        "total_bytes": int(tot), "vs_jxl9_pct": round(100 * (tot / jxl - 1), 3),
        "pexels_bytes": int(sum(per[n]["bytes"] for n in pex)),
        "vs_funnelzip_pct": round(100 * (sum(per[n]["bytes"] for n in pex) / max(1, sum(fz[n] for n in pex)) - 1), 3),
        "kodak_vs_jxl9_pct": round(100 * (sum(per[n]["bytes"] for n in ref if n.startswith("kod")) / sum(ref[n]["jxl9"] for n in ref if n.startswith("kod")) - 1), 3),
        "pexels_vs_jxl9_pct": round(100 * (sum(per[n]["bytes"] for n in ref if n.startswith("pex")) / sum(ref[n]["jxl9"] for n in ref if n.startswith("pex")) - 1), 3),
        "per_image": {n: {"bytes": int(v["bytes"]), "R": int(v["R"]), "G": int(v["G"]), "B": int(v["B"]), "ms": int(v["ms"]),
                          "vs_jxl9_pct": round(100 * (v["bytes"] / ref[n]["jxl9"] - 1), 2),
                          "stats": {k: v[k] for k in ("funnels", "field_born", "field_max", "fission", "prune", "hippo_hit", "replay") if k in v}}
                      for n, v in per.items()},
        "planes": {p: int(sum(v[p] for v in per.values())) for p in "RGB"},
    }
    os.makedirs(LOGDIR, exist_ok=True)
    with open(LOG, "a") as f: f.write(json.dumps(rec) + "\n")
    print(f"{exp['id']:28} {rec['total_bytes']:>11,} B  {rec['vs_jxl9_pct']:+6.2f}% vs JXL  {rec['vs_funnelzip_pct']:+6.2f}% vs FZ  cpu {rec['cpu_s']:6.1f}s", flush=True)
    return rec


def latest(recs):
    out = {}
    for r in recs: out[r["id"]] = r
    return out


def report():
    recs = load_log(); last = latest(recs)
    ref = last.get(REFERENCE)
    L = ["# FFIC experiment log", "",
         "Generated by `ffic/exp.py` from `experiments/log.jsonl` (one JSON record per run; nothing is deleted).",
         "All sizes are **ideal code length** in bytes over 20 images (12 Pexels crops 1024x768, 8 Kodak 768x512).",
         "Reference columns: JXL lossless effort 9; FunnelZip (current compressor, Pexels subset of 11 images only).",
         f"Verdict compares with the reference experiment **{REFERENCE}** (current best, before these experiments): "
         "`helps` < -0.20%, `hurts` > +0.20%, otherwise `neutral`. CPU time is the sum over the 20 images.", ""]
    L += ["## Leaderboard (latest run of each experiment, best first)", "",
          "| # | id | group | vs JXL e9 | vs ref | vs FunnelZip (Pexels) | Pexels vs JXL | Kodak vs JXL | CPU s | x ref time | verdict |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    rows = sorted(last.values(), key=lambda r: r["total_bytes"])
    for i, r in enumerate(rows, 1):
        dv = 100 * (r["total_bytes"] / ref["total_bytes"] - 1) if ref else 0
        verdict = "reference" if r["id"] == REFERENCE else ("helps" if dv < -0.2 else "hurts" if dv > 0.2 else "neutral")
        tx = r["cpu_s"] / ref["cpu_s"] if ref else 1
        L.append(f"| {i} | `{r['id']}` | {r['group']} | {r['vs_jxl9_pct']:+.2f}% | {dv:+.2f}% | {r['vs_funnelzip_pct']:+.2f}% | {r['pexels_vs_jxl9_pct']:+.2f}% | "
                 f"{r['kodak_vs_jxl9_pct']:+.2f}% | {r['cpu_s']:.0f} | {tx:.2f} | {verdict} |")
    # PFC goal bias: the encoder tries every mechanism set and keeps the best per image (+1 header byte to signal it)
    if ref and len(rows) > 1:
        names = list(ref["per_image"]); pick = {}
        for n in names:
            best = min(rows, key=lambda r: r["per_image"].get(n, {"bytes": 1e18})["bytes"])
            pick[n] = (best["id"], best["per_image"][n]["bytes"] + 1)
        tot = sum(b for _, b in pick.values()); jxl = ref["total_bytes"] / (1 + ref["vs_jxl9_pct"] / 100)
        from collections import Counter
        L += ["", "## PFC goal bias: best mechanism set per image (encoder tries all, signals the choice in 1 byte)", "",
              f"Total {tot:,} B = {100 * (tot / jxl - 1):+.2f}% vs JXL e9, {100 * (tot / ref['total_bytes'] - 1):+.2f}% vs `{REFERENCE}`. "
              f"Encode cost = sum of all experiments' time (decode = one). Picks: "
              + ", ".join(f"`{k}` x{v}" for k, v in Counter(i for i, _ in pick.values()).most_common()), ""]
    L += ["", "## Details", ""]
    for r in sorted(last.values(), key=lambda r: [e["id"] for e in EXPERIMENTS].index(r["id"]) if r["id"] in [e["id"] for e in EXPERIMENTS] else 999):
        dv = 100 * (r["total_bytes"] / ref["total_bytes"] - 1) if ref else 0
        L += [f"### `{r['id']}`", "",
              f"* **Mechanism:** {r['mechanism']}",
              f"* **FunnelBrain source:** {r['funnelbrain']}",
              f"* **Hypothesis:** {r['hypothesis']}",
              f"* **Config:** `{r['cfg']}`   code `{r['code_sha1']}` (git {r['git_head']}), run {r['date']}",
              f"* **Result:** {r['total_bytes']:,} B = {r['vs_jxl9_pct']:+.2f}% vs JXL e9, {dv:+.2f}% vs `{REFERENCE}`, "
              f"{r['vs_funnelzip_pct']:+.2f}% vs FunnelZip (Pexels). Planes R/G/B = {r['planes']['R']:,} / {r['planes']['G']:,} / {r['planes']['B']:,}. "
              f"CPU {r['cpu_s']} s (wall {r['wall_s']} s).", ""]
        if ref:
            L += ["| image | bytes | vs JXL | vs ref | stats |", "|---|---|---|---|---|"]
            for n, v in r["per_image"].items():
                rv = ref["per_image"].get(n, {}).get("bytes", 0)
                st = ", ".join(f"{k}={v['stats'][k]:g}" for k in v["stats"] if v["stats"][k])
                L.append(f"| {n} | {v['bytes']:,} | {v['vs_jxl9_pct']:+.2f}% | {100 * (v['bytes'] / rv - 1) if rv else 0:+.2f}% | {st} |")
            wins = sum(1 for n, v in r["per_image"].items() if v["bytes"] < ref["per_image"][n]["bytes"])
            L += ["", f"Better than the reference on {wins} of {len(r['per_image'])} images.", ""]
    L += ["## All runs (chronological)", "", "| date | id | code | total bytes | vs JXL e9 | CPU s |", "|---|---|---|---|---|---|"]
    for r in recs:
        L.append(f"| {r['date']} | `{r['id']}` | {r['code_sha1']} | {r['total_bytes']:,} | {r['vs_jxl9_pct']:+.2f}% | {r['cpu_s']} |")
    open(MD, "w").write("\n".join(L) + "\n")
    print("wrote", MD)


if __name__ == "__main__":
    D = sys.argv[1]; args = sys.argv[2:]
    if args != ["--report"]:
        build()
        fp, _ = fingerprint()
        done = {(r["id"], r["code_sha1"]) for r in load_log()}
        todo = [e for e in EXPERIMENTS if (args == ["--all"] and (e["id"], fp) not in done) or e["id"] in args]
        for e in todo: run_experiment(D, e)
    report()
