"""results/*.json -> docs/REPORT_DATA.md (tables) + outputs/visuals/report.html (charts)."""
from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
load = lambda n: json.loads((R / f"{n}.json").read_text())


def interp_at(curve, x, key):
    """Quality of `curve` at size x (linear in log-bytes). None if x is outside its range."""
    pts = sorted(curve, key=lambda p: p["bytes"])
    for a, b in zip(pts, pts[1:]):
        if a["bytes"] <= x <= b["bytes"]:
            if b["bytes"] == a["bytes"]:
                return a[key]
            t = (math.log(x) - math.log(a["bytes"])) / (math.log(b["bytes"]) - math.log(a["bytes"]))
            return a[key] + t * (b[key] - a[key])
    return None


def gap(ours, theirs, key):
    """Mean quality difference (ours - theirs) at equal size, over the overlapping range."""
    d = [p[key] - q for p in ours if (q := interp_at(theirs, p["bytes"], key)) is not None and math.isfinite(p[key])]
    return (sum(d) / len(d), len(d)) if d else (None, 0)


def elias_cost(b: int) -> int:
    """Bits to store a b-bit number when the decoder does not know b (Elias gamma on b)."""
    return b + 2 * max(1, b).bit_length() - 1


def main() -> None:
    lossless, loop, tree = load("lossless"), load("loop"), load("tree")
    media = {k: load(k) for k in ("image", "audio", "video") if (R / f"{k}.json").exists()}
    md = ["# EquaFile benchmark data (generated by bench/make_report.py)\n"]

    # ---------------- lossless
    md.append("## Lossless: stored bytes (lower is better; every equation row verified bit-exact)\n")
    names = [v["variant"] for v in lossless[0]["variants"]]
    md.append("| file | size | " + " | ".join(names) + " | best existing |")
    md.append("|---|---:|" + "---:|" * len(names) + "---|")
    summary = []
    for e in lossless:
        cells, best_eq = [], None
        for v in e["variants"]:
            if v["status"] == "ok":
                cells.append(f"{v['stored']:,}")
                if best_eq is None or v["stored"] < best_eq[1]:
                    best_eq = (v["variant"], v["stored"])
            else:
                cells.append("–")
        bname, bsize = min(e["baselines"].items(), key=lambda kv: kv[1])
        md.append(f"| {e['file']} | {e['size']:,} | " + " | ".join(cells) + f" | {bname} {bsize:,} |")
        summary.append({"file": e["file"], "size": e["size"], "eq": best_eq, "base": (bname, bsize),
                        "variants": {v["variant"]: v.get("stored") for v in e["variants"]}})
    md.append("")

    # ---------------- loop
    md.append("## Loop / seed search: bits stored vs bits in the file\n")
    md.append("| file bits | V2 loop count (mean bits) | V2 with length prefix | V3 seed (mean bits) | V3 with length prefix | V3 mean search time |")
    md.append("|---:|---:|---:|---:|---:|---:|")
    by = {k: defaultdict(list) for k in ("v2", "v3")}
    for k in by:
        for r in loop[k]:
            by[k][r["bits"]].append(r)
    for n in sorted(set(by["v2"]) | set(by["v3"])):
        row = [str(n)]
        for k in ("v2", "v3"):
            rs = by[k].get(n)
            if rs:
                m = sum(r["stored_bits"] for r in rs) / len(rs)
                me = sum(elias_cost(r["stored_bits"]) for r in rs) / len(rs)
                row += [f"{m:.1f}", f"{me:.1f}"]
            else:
                row += ["–", "–"]
        rs = by["v3"].get(n)
        row.append(f"{sum(r['sec'] for r in rs) / len(rs):.2f} s" if rs else "–")
        md.append("| " + " | ".join(row) + " |")
    md.append("")

    # ---------------- tree
    md.append("## FunnelBrain tree: size per level (bits)\n")
    md.append("| file | " + " | ".join(f"level {i}" for i in range(6)) + " |")
    md.append("|---|" + "---:|" * 6)
    for f, sizes in tree.items():
        md.append(f"| {f} | " + " | ".join(f"{s:,}" for s in sizes) + " |")
    md.append("")

    # ---------------- media
    gaps = {}
    for kind, data in media.items():
        key = "snr" if kind == "audio" else "psnr"
        md.append(f"## {kind.title()}: equal-size quality gap ({key.upper()} dB, equation minus codec)\n")
        md.append("| sample | equation curve | vs | mean gap | points compared |")
        md.append("|---|---|---|---:|---:|")
        for name, e in data.items():
            ours = [k for k in e["curves"] if k.startswith("Equation")]
            others = [k for k in e["curves"] if not k.startswith("Equation")]
            for o in ours:
                for t in others:
                    g, n = gap(e["curves"][o], e["curves"][t], key)
                    gaps[(kind, name, o, t)] = g
                    md.append(f"| {name} | {o} | {t} | {'–' if g is None else f'{g:+.2f}'} | {n} |")
        md.append("")
        md.append(f"### {kind.title()} raw points\n")
        for name, e in data.items():
            md.append(f"**{name}** (raw {e['raw']:,} B" + (f", FLAC {e['flac']:,} B" if "flac" in e else "") +
                      (f", PNG {e['lossless']['PNG']:,} B, WebP-lossless {e['lossless']['WebP lossless']:,} B" if "lossless" in e else "") + ")\n")
            for c, pts in e["curves"].items():
                md.append(f"- {c}: " + ", ".join(f"{p['bytes']:,} B → {p[key]:.1f} dB" for p in pts))
            md.append("")
    (ROOT / "docs" / "REPORT_DATA.md").write_text("\n".join(md))
    print("wrote docs/REPORT_DATA.md")

    payload = {"lossless": summary, "loop": loop, "tree": tree, "media": media,
               "names": {v["variant"]: v["name"] for v in lossless[0]["variants"]}}
    tpl = (ROOT / "bench" / "report_template.html").read_text()
    out = ROOT / "outputs" / "visuals" / "report.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(tpl.replace("/*DATA*/null", json.dumps(payload, default=float)))
    print(f"wrote {out.relative_to(ROOT)}")
    for k, g in gaps.items():
        print(k, None if g is None else round(g, 2))


if __name__ == "__main__":
    main()
